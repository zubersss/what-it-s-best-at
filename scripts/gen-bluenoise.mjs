// Generates a 64x64 blue-noise dither mask with the void-and-cluster method
// (Ulichney 1993) and writes it as src/post/blueNoiseData.js. Output is CC0.
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const N = 64, SIGMA = 1.9, R = 9;
let seed = 1234567;
const rnd = () => ((seed = (seed * 1664525 + 1013904223) >>> 0) / 4294967296);

const kernel = [];
for (let dy = -R; dy <= R; dy++) for (let dx = -R; dx <= R; dx++) kernel.push([dx, dy, Math.exp(-(dx * dx + dy * dy) / (2 * SIGMA * SIGMA))]);

function makeState() { return { bits: new Uint8Array(N * N), energy: new Float64Array(N * N) }; }
function set(st, i, v) {
  if (st.bits[i] === v) return;
  st.bits[i] = v;
  const x = i % N, y = (i / N) | 0, s = v ? 1 : -1;
  for (const [dx, dy, w] of kernel) st.energy[((y + dy + N) % N) * N + ((x + dx + N) % N)] += s * w;
}
function extreme(st, wantBit, findMax) {
  let best = -1, bestE = findMax ? -Infinity : Infinity;
  for (let i = 0; i < N * N; i++) {
    if (st.bits[i] !== wantBit) continue;
    const e = st.energy[i];
    if (findMax ? e > bestE : e < bestE) { bestE = e; best = i; }
  }
  return best;
}

// Initial binary pattern, relaxed until the tightest cluster and largest void coincide.
const init = makeState();
const ones = Math.floor(N * N * 0.1);
for (let k = 0; k < ones;) { const i = Math.floor(rnd() * N * N); if (!init.bits[i]) { set(init, i, 1); k++; } }
for (;;) {
  const c = extreme(init, 1, true); set(init, c, 0);
  const v = extreme(init, 0, false);
  if (v === c) { set(init, c, 1); break; }
  set(init, v, 1);
}

const rank = new Int32Array(N * N).fill(-1);
// Phase 1: remove tightest clusters.
const st = makeState();
for (let i = 0; i < N * N; i++) if (init.bits[i]) set(st, i, 1);
for (let r = ones - 1; r >= 0; r--) { const c = extreme(st, 1, true); set(st, c, 0); rank[c] = r; }
// Phase 2 + 3: fill largest voids.
const st2 = makeState();
for (let i = 0; i < N * N; i++) if (init.bits[i]) set(st2, i, 1);
for (let r = ones; r < N * N; r++) { const v = extreme(st2, 0, false); set(st2, v, 1); rank[v] = r; }

const bytes = Buffer.alloc(N * N);
for (let i = 0; i < N * N; i++) bytes[i] = Math.min(255, Math.floor(rank[i] * 256 / (N * N)));
const out = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../src/post/blueNoiseData.js');
await writeFile(out, `// Generated by scripts/gen-bluenoise.mjs (void-and-cluster, ${N}x${N}). CC0.\nexport const BLUE_NOISE_SIZE = ${N};\nexport const BLUE_NOISE_BASE64 = '${bytes.toString('base64')}';\n`);
console.log('wrote', out);
